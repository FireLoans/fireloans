export function getHemMonthlyByLocation(
  isJoint: boolean,
  location: HemLocation,
  dependents: number,
  grossAnnualIncome: number
): number {
  const clampedDependents = Math.max(0, Math.min(10, Math.round(dependents)));
  const table = isJoint ? HEM_JOINT_V2 : HEM_SINGLE_V2;
  const locationCode = location === "remote" ? "RM" : "RA";
  const row = table[`${locationCode}${clampedDependents}`];
  const band = incomeBandIndexV2(Math.max(0, grossAnnualIncome));
  return row[band];
}
